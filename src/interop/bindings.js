function swiftClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `_ ${camel(parameter.name)}: Any`).join(', ');
    const args = fn.params.map((parameter) => camel(parameter.name)).join(', ');
    return `    /// Calls the exported PlainScript function ${fn.name}.\n    func ${camel(fn.name)}(${params}) throws -> Any {\n        try call(${escapeString(fn.name)}${args ? `, ${args}` : ''})\n    }\n`;
  }).join('\n');

  return `// Generated by PlainScript ${manifest.version} from ${manifest.module}.
// Requires Swift 5.9+ / Foundation. Run the bridge in HTTP mode:
//   plainscript bridge ${entry} --http=8787
import Foundation

struct BridgeError: Error {
    let message: String
}

final class BridgeClient {
    private let baseURL: URL
    private let session: URLSession

    init(baseURL: String = "http://127.0.0.1:8787") {
        self.baseURL = URL(string: baseURL)!
        self.session = URLSession.shared
    }

    func call(_ method: String, _ arguments: Any...) throws -> Any {
        let payload: [String: Any] = ["jsonrpc": "2.0", "id": 1, "method": method, "params": arguments]
        var request = URLRequest(url: baseURL.appendingPathComponent("rpc"))
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "content-type")
        request.httpBody = try JSONSerialization.data(withJSONObject: payload)
        let semaphore = DispatchSemaphore(value: 0)
        var output: Any = NSNull()
        var failureMessage: String?
        session.dataTask(with: request) { data, _, error in
            defer { semaphore.signal() }
            if let error { failureMessage = error.localizedDescription; return }
            guard let data, let message = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                failureMessage = "Invalid bridge response"; return
            }
            if let rpcError = message["error"] as? [String: Any] {
                failureMessage = rpcError["message"] as? String ?? "Bridge error"; return
            }
            output = message["result"] ?? NSNull()
        }.resume()
        semaphore.wait()
        if let failureMessage { throw BridgeError(message: failureMessage) }
        return output
    }

${methods}
}
`;
}

