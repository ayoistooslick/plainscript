function csharpClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `${csharpType(parameter.type)} ${camel(parameter.name)}`).join(', ');
    const args = fn.params.map((parameter) => camel(parameter.name)).join(', ');
    return `    /// <summary>Calls the exported PlainScript function ${fn.name}.</summary>\n    public async Task<JsonElement> ${pascal(fn.name)}Async(${params}) =>\n        await CallAsync(${escapeString(fn.name)}${args ? `, ${args}` : ''});\n`;
  }).join('\n');

  return `// Generated by PlainScript ${manifest.version} from ${manifest.module}.
// Requires .NET 8+. Speaks newline-delimited JSON-RPC 2.0 to
// \`plainscript bridge\`; System.Text.Json ships with the runtime.
using System;
using System.Diagnostics;
using System.Text.Json;
using System.Threading.Tasks;

public sealed class BridgeError : Exception
{
    public int Code { get; }
    public BridgeError(string message, int code = 0) : base(message) { Code = code; }
}

public sealed class BridgeClient : IDisposable
{
    private readonly Process process;
    private readonly JsonSerializerOptions json = new() { PropertyNamingPolicy = null };

    public BridgeClient(string command = "plainscript", string[]? args = null)
    {
        var info = new ProcessStartInfo(command)
        {
            RedirectStandardInput = true,
            RedirectStandardOutput = true,
            UseShellExecute = false,
        };
        foreach (var argument in args ?? new[] { "bridge", ${escapeString(entry)} }) info.ArgumentList.Add(argument);
        process = Process.Start(info) ?? throw new BridgeError("Could not start the PlainScript bridge.");
    }

    public async Task<JsonElement> CallAsync(string method, params object?[] arguments)
    {
        var id = Random.Shared.Next(1, int.MaxValue);
        var request = JsonSerializer.Serialize(new { jsonrpc = "2.0", id, method, @params = arguments }, json);
        await process.StandardInput.WriteLineAsync(request);
        await process.StandardInput.FlushAsync();
        var line = await process.StandardOutput.ReadLineAsync();
        if (line is null) throw new BridgeError("The PlainScript bridge closed the connection.");
        using var document = JsonDocument.Parse(line);
        var root = document.RootElement.Clone();
        if (root.TryGetProperty("error", out var error))
        {
            throw new BridgeError(error.GetProperty("message").GetString() ?? "Bridge error",
                error.TryGetProperty("code", out var code) ? code.GetInt32() : 0);
        }
        return root.TryGetProperty("result", out var result) ? result : default;
    }

${methods}
    public void Dispose()
    {
        process.StandardInput.Close();
        process.WaitForExit(5000);
        process.Dispose();
    }
}
`;
}

