function generateBindings(manifest, languages, entry) {
  const files = [];
  for (const language of normaliseLanguages(languages)) {
    const generator = GENERATORS[language];
    if (!generator) continue;
    files.push({
      language,
      name: generator.file(manifest),
      code: generator.render(manifest, entry || manifest.entry),
    });
  }
  return files;
}

function writeBindings(manifest, languages, directory, entry) {
  const files = generateBindings(manifest, languages, entry);
  fs.mkdirSync(directory, { recursive: true });
  const written = [];
  for (const file of files) {
    const target = path.join(directory, file.name);
    fs.writeFileSync(target, file.code);
    written.push({ ...file, path: target });
  }
  return written;
}

