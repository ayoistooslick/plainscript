const fs = require('fs');
const path = require('path');

// Client generation is driven entirely by the manifest. Each adapter speaks
// the same newline-delimited JSON-RPC 2.0 protocol as `plainscript bridge`, so
// adding a language is one template, not one compiler change.
//
// The generated clients are deliberately small: no PlainScript runtime, no
// native addon, no build step beyond the target language's own toolchain.

const LANGUAGE_ALIASES = Object.freeze({
  js: 'javascript',
  javascript: 'javascript',
  mjs: 'javascript',
  node: 'javascript',
  py: 'python',
  python: 'python',
  python3: 'python',
  go: 'go',
  golang: 'go',
  rs: 'rust',
  rust: 'rust',
  java: 'java',
  kt: 'kotlin',
  kotlin: 'kotlin',
  rb: 'ruby',
  ruby: 'ruby',
  php: 'php',
  cs: 'csharp',
  csharp: 'csharp',
  'c#': 'csharp',
  swift: 'swift',
  dart: 'dart',
  c: 'c',
  cpp: 'cpp',
  'c++': 'cpp',
});

const SUPPORTED = [...new Set(Object.values(LANGUAGE_ALIASES))].sort();

function normaliseLanguages(languages) {
  const list = [];
  for (const language of languages) {
    const key = String(language).toLowerCase();
    const resolved = LANGUAGE_ALIASES[key];
    if (!resolved) throw new Error(`Unknown interop language "${language}". Supported: ${SUPPORTED.join(', ')}.`);
    if (!list.includes(resolved)) list.push(resolved);
  }
  return list;
}

function snake(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9_]/g, '_').toLowerCase();
}

function pascal(name) {
  return name.replace(/[^A-Za-z0-9]+/g, ' ').split(' ').filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1)).join('');
}

function camel(name) {
  const upper = pascal(name);
  return upper ? upper[0].toLowerCase() + upper.slice(1) : upper;
}

function escapeString(text) {
  return JSON.stringify(String(text));
}

function baseType(type) {
  if (!type) return 'any';
  if (type.optional && type.kind !== 'union') return `${type.kind}`;
  return type.kind;
}

// --------------------------------------------------------------------- Python

const PYTHON_RESERVED = new Set([
  'False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break', 'class',
  'continue', 'def', 'del', 'elif', 'else', 'except', 'finally', 'for', 'from', 'global',
  'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or', 'pass', 'raise', 'return',
  'try', 'while', 'with', 'yield', 'match', 'case', 'type', 'list', 'dict', 'str', 'int',
]);

function pyName(name) {
  const value = snake(name);
  return PYTHON_RESERVED.has(value) ? `${value}_` : value;
}

function pyType(type) {
  const kind = baseType(type);
  switch (kind) {
    case 'text': return 'str';
    case 'number': return 'float';
    case 'boolean': return 'bool';
    case 'list': return 'list[Any]';
    case 'map': return 'dict[str, Any]';
    default: return 'Any';
  }
}

function pythonClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `${pyName(parameter.name)}: ${pyType(parameter.type)}${parameter.optional ? ' = None' : ''}`).join(', ');
    const args = fn.params.map((parameter) => pyName(parameter.name)).join(', ');
    return `    def ${pyName(fn.name)}(self, ${params}) -> Any:\n        return self.call(${escapeString(fn.name)}${args ? `, ${args}` : ''})\n`;
  }).join('\n');

  return `"""Generated by PlainScript ${manifest.version} from ${manifest.module}.

Requires Python 3.9+. The client starts \`plainscript bridge\` as a child
process and speaks newline-delimited JSON-RPC 2.0; no PlainScript runtime is
imported into Python.

    from ${snake(manifest.module)}_bridge import Client
    with Client() as client:
        print(client.${pyName(manifest.functions[0] ? manifest.functions[0].name : 'call')}(...))
"""
from __future__ import annotations

import json
import subprocess
import threading
from typing import Any

__all__ = ["Client", "BridgeError", "connect"]


class BridgeError(RuntimeError):
    """Raised when the PlainScript bridge reports an error."""

    def __init__(self, message: str, code: int = 0, data: Any = None) -> None:
        super().__init__(message)
        self.code = code
        self.data = data


class Client:
    def __init__(self, command: str = "plainscript", args: list[str] | None = None,
                 cwd: str | None = None) -> None:
        argv = [command, *(args if args is not None else ["bridge", ${escapeString(entry)}])]
        self._process = subprocess.Popen(
            argv,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            text=True,
            bufsize=1,
            cwd=cwd,
        )
        self._id = 0
        self._lock = threading.Lock()

    def call(self, method: str, *args: Any) -> Any:
        with self._lock:
            self._id += 1
            payload = {"jsonrpc": "2.0", "id": self._id, "method": method, "params": list(args)}
            assert self._process.stdin is not None and self._process.stdout is not None
            self._process.stdin.write(json.dumps(payload) + "\\n")
            self._process.stdin.flush()
            line = self._process.stdout.readline()
            if not line:
                raise BridgeError("The PlainScript bridge closed the connection.")
            message = json.loads(line)
            if "error" in message:
                error = message["error"]
                raise BridgeError(error.get("message", "Bridge error"), error.get("code", 0), error.get("data"))
            return message.get("result")

    def notify(self, method: str, *args: Any) -> None:
        with self._lock:
            payload = {"jsonrpc": "2.0", "method": method, "params": list(args)}
            assert self._process.stdin is not None
            self._process.stdin.write(json.dumps(payload) + "\\n")
            self._process.stdin.flush()

${methods}
    def close(self) -> None:
        if self._process.poll() is None:
            try:
                assert self._process.stdin is not None
                self._process.stdin.close()
            except OSError:
                pass
            try:
                self._process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self._process.terminate()

    def __enter__(self) -> "Client":
        return self

    def __exit__(self, *_: Any) -> None:
        self.close()


def connect(command: str = "plainscript", args: list[str] | None = None,
            cwd: str | None = None) -> Client:
    return Client(command=command, args=args, cwd=cwd)
`;
}

// ----------------------------------------------------------------- JavaScript

function javascriptClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => camel(parameter.name)).join(', ');
    return `  async ${camel(fn.name)}(${params}) {\n    return this.call(${escapeString(fn.name)}${params ? `, ${params}` : ''});\n  }\n`;
  }).join('\n');

  return `// Generated by PlainScript ${manifest.version} from ${manifest.module}.
// Requires Node 18+. Speaks newline-delimited JSON-RPC 2.0 to
// \`plainscript bridge\`; no PlainScript runtime is imported.

import { spawn } from "node:child_process";
import readline from "node:readline";

export class BridgeError extends Error {
  constructor(message, code = 0, data = undefined) {
    super(message);
    this.name = "BridgeError";
    this.code = code;
    this.data = data;
  }
}

export class Client {
  constructor(command = "plainscript", args = ["bridge", ${escapeString(entry)}], options = {}) {
    this.process = spawn(command, args, { stdio: ["pipe", "pipe", options.stderr || "inherit"] });
    this.pending = new Map();
    this.nextId = 1;
    this.reader = readline.createInterface({ input: this.process.stdout, crlfDelay: Infinity });
    this.reader.on("line", (line) => {
      let message;
      try {
        message = JSON.parse(line);
      } catch {
        return;
      }
      const entryPoint = this.pending.get(message.id);
      if (!entryPoint) return;
      this.pending.delete(message.id);
      if (message.error) entryPoint.reject(new BridgeError(message.error.message, message.error.code, message.error.data));
      else entryPoint.resolve(message.result);
    });
    this.process.on("exit", (code) => {
      for (const entryPoint of this.pending.values()) {
        entryPoint.reject(new BridgeError(\`The PlainScript bridge exited with code \${code}.\`));
      }
      this.pending.clear();
    });
  }

  call(method, ...args) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.process.stdin.write(\`\${JSON.stringify({ jsonrpc: "2.0", id, method, params: args })}\\n\`);
    });
  }

  notify(method, ...args) {
    this.process.stdin.write(\`\${JSON.stringify({ jsonrpc: "2.0", method, params: args })}\\n\`);
  }

${methods}
  close() {
    this.reader.close();
    this.process.stdin.end();
  }
}

export function connect(options = {}) {
  return new Client(options.command, options.args, options);
}
`;
}

// ------------------------------------------------------------------------ Go

function goType(type) {
  const kind = baseType(type);
  switch (kind) {
    case 'text': return 'string';
    case 'number': return 'float64';
    case 'boolean': return 'bool';
    case 'list': return '[]any';
    case 'map': return 'map[string]any';
    default: return 'any';
  }
}

function goClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `${camel(parameter.name)} ${goType(parameter.type)}`).join(', ');
    const args = fn.params.map((parameter) => camel(parameter.name)).join(', ');
    return `// ${pascal(fn.name)} calls the exported PlainScript function ${fn.name}.\nfunc (c *Client) ${pascal(fn.name)}(${params}) (any, error) {\n\treturn c.Call(${escapeString(fn.name)}${args ? `, ${args}` : ''})\n}\n`;
  }).join('\n');

  return `// Code generated by PlainScript ${manifest.version} from ${manifest.module}. DO NOT EDIT.
// Package ${snake(manifest.module)} calls a PlainScript bridge over
// newline-delimited JSON-RPC 2.0. Only the Go standard library is required.
package ${snake(manifest.module)}

import (
\t"bufio"
\t"encoding/json"
\t"fmt"
\t"io"
\t"os/exec"
\t"sync"
)

type response struct {
\tResult any \`json:"result"\`
\tError  *struct {
\t\tCode    int    \`json:"code"\`
\t\tMessage string \`json:"message"\`
\t\tData    any    \`json:"data"\`
\t} \`json:"error"\`
}

type Client struct {
\tcommand string
\targs    []string
\tprocess *exec.Cmd
\tstdin   io.WriteCloser
\tstdout  *bufio.Reader
\tnextID  int
\tmutex   sync.Mutex
}

// Connect starts "plainscript bridge <entry>".
func Connect() (*Client, error) {
\treturn ConnectCommand("plainscript", "bridge", ${escapeString(entry)})
}

// ConnectCommand starts an arbitrary bridge command.
func ConnectCommand(command string, args ...string) (*Client, error) {
\tprocess := exec.Command(command, args...)
\tstdin, err := process.StdinPipe()
\tif err != nil { return nil, err }
\tstdout, err := process.StdoutPipe()
\tif err != nil { return nil, err }
\tif err := process.Start(); err != nil { return nil, err }
\treturn &Client{command: command, args: args, process: process, stdin: stdin, stdout: bufio.NewReader(stdout)}, nil
}

// Call invokes one exported PlainScript function.
func (c *Client) Call(method string, params ...any) (any, error) {
\tc.mutex.Lock()
\tdefer c.mutex.Unlock()
\tc.nextID++
\trequest := map[string]any{"jsonrpc": "2.0", "id": c.nextID, "method": method, "params": params}
\tencoded, err := json.Marshal(request)
\tif err != nil { return nil, err }
\tif _, err := fmt.Fprintf(c.stdin, "%s\\n", encoded); err != nil { return nil, err }
\tline, err := c.stdout.ReadString('\\n')
\tif err != nil { return nil, err }
\tvar message response
\tif err := json.Unmarshal([]byte(line), &message); err != nil { return nil, err }
\tif message.Error != nil { return nil, fmt.Errorf("plainscript bridge: %s (code %d)", message.Error.Message, message.Error.Code) }
\treturn message.Result, nil
}

${methods}
// Close terminates the bridge process.
func (c *Client) Close() error {
\t_ = c.stdin.Close()
\treturn c.process.Wait()
}
`;
}

// ---------------------------------------------------------------------- Rust

function rustType(type) {
  const kind = baseType(type);
  switch (kind) {
    case 'text': return 'String';
    case 'number': return 'f64';
    case 'boolean': return 'bool';
    case 'list': return 'Vec<serde_json::Value>';
    default: return 'serde_json::Value';
  }
}

function rustClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `${snake(parameter.name)}: ${rustType(parameter.type)}`).join(', ');
    const args = fn.params.map((parameter) => `serde_json::json!(${snake(parameter.name)})`).join(', ');
    return `    /// Calls the exported PlainScript function ${fn.name}.\n    pub fn ${snake(fn.name)}(&mut self, ${params}) -> Result<serde_json::Value, BridgeError> {\n        self.call(${escapeString(fn.name)}, serde_json::json!([${args}]))\n    }\n`;
  }).join('\n');

  return `// Generated by PlainScript ${manifest.version} from ${manifest.module}.
// Requires serde_json (add \`serde_json = "1"\` to Cargo.toml). Speaks
// newline-delimited JSON-RPC 2.0 to \`plainscript bridge\`.
use serde_json::Value;
use std::io::{BufRead, BufReader, Write};
use std::process::{Child, ChildStdin, ChildStdout, Command, Stdio};

#[derive(Debug)]
pub struct BridgeError(pub String);

impl std::fmt::Display for BridgeError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "{}", self.0)
    }
}

impl std::error::Error for BridgeError {}

pub struct Client {
    child: Child,
    stdin: ChildStdin,
    stdout: BufReader<ChildStdout>,
    next_id: u64,
}

impl Client {
    pub fn connect() -> Result<Self, BridgeError> {
        Self::connect_command("plainscript", &["bridge", ${escapeString(entry)}])
    }

    pub fn connect_command(command: &str, args: &[&str]) -> Result<Self, BridgeError> {
        let mut child = Command::new(command)
            .args(args)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .spawn()
            .map_err(|error| BridgeError(error.to_string()))?;
        let stdin = child.stdin.take().ok_or_else(|| BridgeError("missing stdin".into()))?;
        let stdout = child.stdout.take().ok_or_else(|| BridgeError("missing stdout".into()))?;
        Ok(Self { child, stdin, stdout: BufReader::new(stdout), next_id: 0 })
    }

    pub fn call(&mut self, method: &str, params: Value) -> Result<Value, BridgeError> {
        self.next_id += 1;
        let request = serde_json::json!({
            "jsonrpc": "2.0", "id": self.next_id, "method": method, "params": params
        });
        writeln!(self.stdin, "{}", request).map_err(|error| BridgeError(error.to_string()))?;
        self.stdin.flush().map_err(|error| BridgeError(error.to_string()))?;
        let mut line = String::new();
        self.stdout.read_line(&mut line).map_err(|error| BridgeError(error.to_string()))?;
        let message: Value = serde_json::from_str(&line).map_err(|error| BridgeError(error.to_string()))?;
        if let Some(error) = message.get("error") {
            return Err(BridgeError(error.to_string()));
        }
        Ok(message.get("result").cloned().unwrap_or(Value::Null))
    }

${methods}
    pub fn close(mut self) -> std::io::Result<()> {
        drop(self.stdin);
        self.child.wait().map(|_| ())
    }
}
`;
}

