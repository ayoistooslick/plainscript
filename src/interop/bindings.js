function javaClient(manifest, entry) {
  const methods = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `${javaType(parameter.type)} ${camel(parameter.name)}`).join(', ');
    const args = fn.params.map((parameter) => camel(parameter.name)).join(', ');
    return `    /** Calls the exported PlainScript function ${fn.name}. Returns raw JSON. */\n    public String ${camel(fn.name)}(${params}) throws IOException, InterruptedException {\n        return call(${escapeString(fn.name)}${args ? `, ${args}` : ''});\n    }\n`;
  }).join('\n');

  return `// Generated by PlainScript ${manifest.version} from ${manifest.module}.
// Requires Java 11+ (java.net.http). Responses are returned as raw JSON so the
// client has no third-party dependency; parse with Jackson or Gson if needed.
// Start the bridge in HTTP mode first:
//   plainscript bridge ${entry} --http=8787
import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.util.StringJoiner;

public final class BridgeClient {
    private final String url;
    private final HttpClient http = HttpClient.newHttpClient();

    public BridgeClient(String url) {
        this.url = url.replaceAll("/$", "");
    }

    public String call(String method, Object... args) throws IOException, InterruptedException {
        StringJoiner params = new StringJoiner(",", "[", "]");
        for (Object arg : args) params.add(json(arg));
        String body = "{\\"jsonrpc\\":\\"2.0\\",\\"id\\":1,\\"method\\":" + json(method) + ",\\"params\\":" + params + "}";
        HttpRequest request = HttpRequest.newBuilder(URI.create(url + "/rpc"))
            .header("content-type", "application/json")
            .POST(HttpRequest.BodyPublishers.ofString(body))
            .build();
        HttpResponse<String> response = http.send(request, HttpResponse.BodyHandlers.ofString());
        return response.body();
    }

    private static String json(Object value) {
        if (value == null) return "null";
        if (value instanceof Number || value instanceof Boolean) return value.toString();
        return "\\"" + String.valueOf(value).replace("\\\\", "\\\\\\\\").replace("\\"", "\\\\\\"") + "\\"";
    }

${methods}
}
`;
}

