function cClient(manifest, entry) {
  const declarations = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `const char* ${snake(parameter.name)}`).join(', ');
    const values = fn.params.map((parameter) => snake(parameter.name)).join(', ');
    return `/* ${fn.name}: arguments are raw JSON fragments; returns a malloc'd JSON result. */\nchar* ps_${snake(fn.name)}(${params || 'void'});`;
  }).join('\n');

  const definitions = manifest.functions.map((fn) => {
    const params = fn.params.map((parameter) => `const char* ${snake(parameter.name)}`).join(', ');
    const values = fn.params.length
      ? `    const char* ps_values[] = { ${fn.params.map((parameter) => snake(parameter.name)).join(', ')} };\n    char* args = ps_args(${fn.params.length}, ps_values);`
      : '    char* args = ps_args(0, NULL);';
    return `char* ps_${snake(fn.name)}(${params || 'void'}) {\n${values}\n    char* result = ps_call(PS_ENTRY, ${escapeString(fn.name)}, args);\n    free(args);\n    return result;\n}`;
  }).join('\n\n');

  return `/* Generated by PlainScript ${manifest.version} from ${manifest.module}.
 *
 * One-shot C client for the PlainScript bridge. It uses popen(3), so it is
 * POSIX-only and needs no JSON library: each argument is a raw JSON fragment
 * ("\\"text\\"", "42", "[1,2]") and the bridge's JSON result is returned as a
 * malloc'd string. Free results with ps_free().
 *
 *   plainscript bridge ${entry} --call=<method> --args '<json-array>'
 *
 * Compile with:  cc example.c -o example
 */
#ifndef PLAINSCRIPT_${snake(manifest.module).toUpperCase()}_BRIDGE_H
#define PLAINSCRIPT_${snake(manifest.module).toUpperCase()}_BRIDGE_H

#define _POSIX_C_SOURCE 200809L

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#ifndef PS_ENTRY
#define PS_ENTRY ${escapeString(entry)}
#endif

#ifndef PS_COMMAND
#define PS_COMMAND "plainscript"
#endif

/* Builds a JSON array from raw JSON fragments. NULL becomes null. */
static char* ps_args(int count, const char* const* values) {
    size_t size = 3;
    for (int index = 0; index < count; index += 1) {
        size += (values[index] ? strlen(values[index]) : 4) + 2;
    }
    char* output = (char*)malloc(size);
    if (!output) return NULL;
    size_t cursor = 0;
    output[cursor++] = '[';
    for (int index = 0; index < count; index += 1) {
        if (index > 0) output[cursor++] = ',';
        const char* value = values[index] ? values[index] : "null";
        size_t length = strlen(value);
        memcpy(output + cursor, value, length);
        cursor += length;
    }
    output[cursor++] = ']';
    output[cursor] = '\\0';
    return output;
}

/* Runs one bridge call and returns the raw JSON response. */
static char* ps_call(const char* entry, const char* method, const char* args_json) {
    char command[8192];
    snprintf(command, sizeof(command), "%s bridge %s --call=%s --args '%s' 2>/dev/null", PS_COMMAND, entry, method, args_json ? args_json : "[]");
    FILE* pipe = popen(command, "r");
    if (!pipe) return NULL;
    size_t capacity = 4096;
    size_t length = 0;
    char* buffer = (char*)malloc(capacity);
    if (!buffer) { pclose(pipe); return NULL; }
    size_t read;
    while ((read = fread(buffer + length, 1, capacity - length - 1, pipe)) > 0) {
        length += read;
        if (length + 1 >= capacity) {
            capacity *= 2;
            char* larger = (char*)realloc(buffer, capacity);
            if (!larger) { free(buffer); pclose(pipe); return NULL; }
            buffer = larger;
        }
    }
    buffer[length] = '\\0';
    pclose(pipe);
    return buffer;
}

static void ps_free(char* value) { free(value); }

${declarations}

${definitions}

#endif
`;
}

